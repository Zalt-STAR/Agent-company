import { TILE } from './config.js';

// Legend: # ground  = platform  o coin  ^ spikes  P spawn  F goal flag
const MAP = [
  '............................................................',
  '............................................................',
  '............................................................',
  '............................................................',
  '............................................................',
  '...........................................ooo..............',
  '...........................................===..............',
  '................ooo.........................................',
  '...............=====........................................',
  '..........................oo......oo...===..................',
  '.....ooo..................##.........................oo.....',
  '..P...........................^^..........^^.............F..',
  '##########...########..##########...############...#########',
  '##########...########..##########...############...#########',
];

export function loadLevel() {
  const height = MAP.length;
  const width = MAP[0].length;
  const coins = [];
  const spikes = [];
  let spawn = { x: TILE, y: TILE };
  let goal = null;

  MAP.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === 'o') coins.push({ x, y, taken: false });
      else if (c === '^') spikes.push({ x, y });
      else if (c === 'P') spawn = { x: x * TILE + 5, y: y * TILE + 4 };
      else if (c === 'F') goal = { x, y };
    }),
  );

  return {
    width,
    height,
    coins,
    spikes,
    goal,
    spawn,
    coinsTotal: coins.length,
    collected: 0,
    tileAt: (tx, ty) => MAP[ty]?.[tx] ?? '.',
    isSolid(tx, ty) {
      if (tx < 0 || tx >= width) return true;
      const c = MAP[ty]?.[tx];
      return c === '#' || c === '=';
    },
  };
}
